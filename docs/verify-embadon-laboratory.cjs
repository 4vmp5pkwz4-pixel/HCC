#!/usr/bin/env node
/* ============================================================================
   THE EMBADON LABORATORY, CHECKED AGAINST SOMETHING ELSE

   An embadon is one atom of the molecular decomposition of the capacity measure on the
   carrier CP1 = S2. The CIVP chain already weighs them and already keeps q_can apart from
   N_emb. What it never drew is the SPACE they live in, and that space is four dimensional
   as soon as there are two of them:

       Sym^N(CP1) = CP^N

   This file does not ask the atlas's kernels whether they like their own answers. Every
   claim is recomputed by a route that shares no code with them:

     - the binary form is rebuilt from VIETA's elementary symmetric functions, written
       here, and compared with the convolution the atlas uses;
     - the roots are recovered by a Durand-Kerner iteration and the residual |P(z)| at
       every returned root is measured, not assumed;
     - all N! orderings are generated by a permutation routine written here;
     - the moment map is checked to land on the standard simplex and its vertices are
       hit exactly;
     - the discriminant is checked against the closed-form quadratic and CUBIC
       discriminants, which share nothing with the product over pairs;
     - the braid is checked twice: by continuing the roots, and by accumulating the
       argument of p^2 - 4q, which must wind by exactly 2 pi per turn;
     - and the isoclinic rotation's orbits are fed to the atlas's own Gauss linking
       integral, which returns 1 — because those orbits ARE the Hopf fibration.

   Run: node docs/verify-embadon-laboratory.cjs
   ========================================================================= */

let pass = 0, fail = 0;
const ok = (t, c, d) => { c ? pass++ : fail++;
  console.log(`${c ? '  PASS' : '  FAIL'} — ${t}`); if (d) console.log(`         ${d}`); };

(async () => {
const { pathToFileURL } = require('node:url');
const { join } = require('node:path');
const X = await import(pathToFileURL(join(__dirname, '..', 'core/atlas/extracted.mjs')).href);
const C = (r = 0, i = 0) => ({ re: r, im: i });
const mul = (a, b) => C(a.re * b.re - a.im * b.im, a.re * b.im + a.im * b.re);
const add = (a, b) => C(a.re + b.re, a.im + b.im);
const sub = (a, b) => C(a.re - b.re, a.im - b.im);
const abs = a => Math.hypot(a.re, a.im);
const perms = a => { if (a.length <= 1) return [a]; const out = [];
  for (let i = 0; i < a.length; i++) { const rest = a.slice(0, i).concat(a.slice(i + 1));
    for (const r of perms(rest)) out.push([a[i]].concat(r)); } return out; };

console.log('\n1 · Sym^N(CP1) = CP^N — the identification, verified rather than asserted\n');
{
  /* VIETA, written here: the coefficient of X^(N-k) in prod (X - z_i) is
     (-1)^k times the k-th elementary symmetric function of the roots. That is a sum over
     subsets and shares no code with the atlas's running convolution. */
  const vieta = roots => {
    const N = roots.length, out = [];
    for (let k = 0; k <= N; k++) {
      let e = C(0, 0);
      const idx = new Array(k).fill(0).map((_, j) => j);
      if (k === 0) { out.push(C(1, 0)); continue; }
      const rec = (start, depth, prod) => {
        if (depth === k) { e = add(e, prod); return; }
        for (let j = start; j < N; j++) rec(j + 1, depth + 1, mul(prod, roots[j]));
      };
      rec(0, 0, C(1, 0));
      out.push(k % 2 ? C(-e.re, -e.im) : e);
    }
    return out;
  };
  let worstV = 0, worstR = 0, worstP = 0, rows = [];
  for (const N of [2, 3, 5, 8, 12]) {
    const roots = X.embPositions(N, 'spiral', 7).map(q => X.embZFromSphere(q));
    const c = X.embFormFromRoots(roots), v = vieta(roots);
    let dv = 0; for (let k = 0; k <= N; k++) dv = Math.max(dv, abs(sub(c[k], v[k])));
    const back = X.embRootsOfMonic(c, 400);
    const dr = X.embMatchRoots(roots, back);
    /* The residual of the recovered roots in the polynomial itself — RELATIVE to the size of
       the terms that build it. The absolute residual is not a measure of anything on its own:
       at N = 12 the stereographic coefficients reach 1e8, so 1e-8 of absolute residual is the
       floating-point floor of the evaluation and not a disagreement with anything. */
    let dp = 0;
    for (const z of back) {
      let s = C(0, 0), scale = 0;
      for (let k = 0; k <= N; k++) { s = add(mul(s, z), c[k]); scale = scale * abs(z) + abs(c[k]); }
      dp = Math.max(dp, abs(s) / Math.max(1e-300, scale));
    }
    worstV = Math.max(worstV, dv); worstR = Math.max(worstR, dr); worstP = Math.max(worstP, dp);
    rows.push(`N=${N}: vieta ${dv.toExponential(1)}, round trip ${dr.toExponential(1)}, relative |P(z)| ${dp.toExponential(1)}`);
  }
  ok('the binary form the atlas builds by convolution IS the one Vieta writes as elementary symmetric functions, and the roots come back out of it — at five degrees, with the polynomial residual at the recovered roots measured rather than trusted',
    worstV < 1e-13 && worstR < 1e-13 && worstP < 1e-15,
    rows.join(' · '));
}

{
  /* THE 1/N!, GENERATED. Every ordering of the atoms must land on the same point of CP^N,
     and for N = 6 that is all 720 of them. */
  let worst = 0, tried = 0;
  const roots = X.embPositions(6, 'spiral', 7).map(q => X.embZFromSphere(q));
  const c0 = X.embFormFromRoots(roots);
  for (const q of perms(roots)) { const c = X.embFormFromRoots(q); tried++;
    for (let k = 0; k < c.length; k++) worst = Math.max(worst, abs(sub(c[k], c0[k]))); }
  ok('all 720 orderings of six embadons are ONE point of CP^6 — the unordered configuration space is not a quotient taken by hand, it is what the coefficients already are',
    tried === 720 && worst < 1e-14,
    `${tried} orderings, worst coefficient disagreement ${worst.toExponential(2)} · this is the 1/N! of the bosonic quotient, and section 4 shows where its generator comes from`);
}

console.log('\n2 · the moment polytope and the torus fibre — all four real dimensions\n');
{
  const roots = X.embPositions(2, 'spiral', 7).map(q => X.embZFromSphere(q));
  const c = X.embFormFromRoots(roots), mu = X.embMoment(c), ang = X.embTorusAngles(c);
  /* the image is the standard simplex, and the vertices are hit exactly */
  const e0 = [C(1, 0), C(0, 0), C(0, 0)], e1 = [C(0, 0), C(1, 0), C(0, 0)], e2 = [C(0, 0), C(0, 0), C(1, 0)];
  const isVertex = (v, k) => X.embMoment(v).every((x, j) => Math.abs(x - (j === k ? 1 : 0)) < 1e-15);
  ok('the moment map lands on the STANDARD simplex — the coordinates are non-negative and sum to one exactly — and the three coordinate points are its three vertices, hit to the last bit',
    Math.abs(mu.reduce((a, b) => a + b, 0) - 1) < 1e-15 && mu.every(x => x >= 0) &&
    isVertex(e0, 0) && isVertex(e1, 1) && isVertex(e2, 2) && mu.length === 3 && ang.length === 2,
    `mu = (${mu.map(x => x.toFixed(6)).join(', ')}), sum ${mu.reduce((a, b) => a + b, 0).toFixed(16)} · ` +
    `two polytope coordinates and ${ang.length} angles is four real dimensions, which is the dimension of Sym^2(CP1) = CP^2`);

  /* scale invariance: a point of PROJECTIVE space does not know its representative */
  let worst = 0;
  for (const s of [C(3, 0), C(0, -1), C(0.001, 0.001), C(-7, 4)]) {
    const cs = c.map(a => mul(a, s)), ms = X.embMoment(cs);
    for (let k = 0; k < ms.length; k++) worst = Math.max(worst, Math.abs(ms[k] - mu[k]));
  }
  ok('and it is a function on PROJECTIVE space: rescaling every coefficient by any complex number, including a tiny one and a negative one, does not move the moment point',
    worst < 1e-14, `worst coordinate drift over four rescalings ${worst.toExponential(2)}`);
}

{
  /* Fubini-Study: the metric of the space both divisors live in */
  const e = k => [0, 1, 2].map(j => C(j === k ? 1 : 0, 0));
  const mix = [C(1, 0), C(1, 0), C(0, 0)];
  let tri = 0, worstTri = 0;
  for (let a = 0; a < 40; a++) {
    const P = k => [C(Math.sin(a + k), Math.cos(2 * a - k)), C(Math.cos(a * 1.7 + k), Math.sin(a - 3 * k)), C(Math.sin(2.3 * a + k), 0.4)];
    const A = P(0), B = P(1), D = P(2);
    const ab = X.embFubiniStudy(A, B), bd = X.embFubiniStudy(B, D), ad = X.embFubiniStudy(A, D);
    if (ad <= ab + bd + 1e-12) tri++; worstTri = Math.max(worstTri, ad - ab - bd);
  }
  ok('the Fubini-Study distance is a metric on that space: orthogonal divisors sit exactly pi/2 apart, an equal superposition exactly pi/4, a point is at zero from itself, and the triangle inequality holds at forty random triples',
    Math.abs(X.embFubiniStudy(e(0), e(1)) - Math.PI / 2) < 1e-15 &&
    Math.abs(X.embFubiniStudy(e(0), mix) - Math.PI / 4) < 1e-12 &&
    X.embFubiniStudy(e(0), e(0)) === 0 && tri === 40,
    `d(e0,e1) = ${X.embFubiniStudy(e(0), e(1)).toFixed(15)} against pi/2 = ${(Math.PI / 2).toFixed(15)} · ` +
    `d(e0, e0+e1) = ${X.embFubiniStudy(e(0), mix).toFixed(12)} against pi/4 · triangle inequality ${tri}/40, worst slack ${worstTri.toExponential(1)}`);
}

console.log('\n3 · the discriminant, where two embadons collide\n');
{
  const r2 = [C(0.3, 0.4), C(-1.1, 0.2)];
  const c2 = X.embFormFromRoots(r2);
  /* the QUADRATIC discriminant p^2 - 4q, written here */
  const q2 = { re: c2[1].re * c2[1].re - c2[1].im * c2[1].im - 4 * c2[2].re,
               im: 2 * c2[1].re * c2[1].im - 4 * c2[2].im };
  const d2 = X.embDiscriminant(r2);
  /* the CUBIC discriminant 18abcd - 4b^3 d + b^2 c^2 - 4ac^3 - 27a^2 d^2, also written here */
  const r3 = [C(0.7, -0.2), C(-0.4, 0.9), C(1.3, 0.35)];
  const c3 = X.embFormFromRoots(r3);
  const [a, b, cc, dd] = [C(1, 0), c3[1], c3[2], c3[3]];
  const k = (x, n) => C(x.re * n, x.im * n);
  const q3 = add(add(add(add(k(mul(mul(a, b), mul(cc, dd)), 18), k(mul(mul(b, mul(b, b)), dd), -4)),
    mul(mul(b, b), mul(cc, cc))), k(mul(a, mul(cc, mul(cc, cc))), -4)), k(mul(mul(a, a), mul(dd, dd)), -27));
  const d3 = X.embDiscriminant(r3);
  ok('the product over pairs IS the classical discriminant, at degree two and at degree three, where the closed forms share nothing with it — and it is exactly zero when two atoms coincide',
    abs(sub(d2, q2)) < 1e-13 && abs(sub(d3, q3)) < 1e-11 &&
    X.civpCabs(X.embDiscriminant([C(0.5, 0.5), C(0.5, 0.5)])) === 0 &&
    X.embSeparation([C(0.5, 0.5), C(0.5, 0.5)]) === 0,
    `degree 2: ${d2.re.toFixed(10)}${d2.im < 0 ? '' : '+'}${d2.im.toFixed(10)}i against p^2-4q, difference ${abs(sub(d2, q2)).toExponential(1)} · ` +
    `degree 3: difference ${abs(sub(d3, q3)).toExponential(1)} from 18abcd - 4b^3d + b^2c^2 - 4ac^3 - 27a^2d^2`);
}

console.log('\n4 · the braid — where the 1/N! actually comes from\n');
{
  const p = C(0.6, -0.35), rho = 0.8;
  const rows = [];
  let good = true;
  for (const turns of [1, 2, 3, 4, 5, 6]) {
    const m = X.embMonodromy(p, rho, turns, 4000);
    const want = turns % 2 === 1;
    if (m.exchanged !== want || m.closure_defect > 1e-12) good = false;
    rows.push(`${turns}: ${m.exchanged ? 'swap' : 'identity'} (${m.closure_defect.toExponential(0)})`);
  }
  ok('a loop around the collision locus EXCHANGES the two embadons, and going round again brings them back: odd turns swap, even turns do not, at six winding numbers, with the continued path closing to the floating-point floor',
    good, rows.join(' · ') + ' · pi_1(C^2 minus Delta) = Z and it surjects onto S_2 — the symmetric group whose order is the N! the bosonic measure divides by');

  /* THE SECOND ROUTE. The two roots are (-p +- sqrt(p^2 - 4q))/2, so the exchange is
     exactly the sign change of a square root — and that happens if and only if the
     argument of p^2 - 4q winds by an odd multiple of 2 pi. Accumulate it and count. */
  const windings = turns => {
    let acc = 0, prev = null;
    const M = 20000;
    for (let s = 0; s <= M; s++) {
      const q = X.embBraidQ(p, rho, turns * s / M);
      const disc = C(p.re * p.re - p.im * p.im - 4 * q.re, 2 * p.re * p.im - 4 * q.im);
      const th = Math.atan2(disc.im, disc.re);
      if (prev !== null) { let d = th - prev; while (d > Math.PI) d -= 2 * Math.PI; while (d < -Math.PI) d += 2 * Math.PI; acc += d; }
      prev = th;
    }
    return acc / (2 * Math.PI);
  };
  const w1 = windings(1), w2 = windings(2), w3 = windings(3);
  ok('and the same answer arrives by a route with no root finding in it at all: the discriminant p^2 - 4q winds around zero exactly once per turn, so its square root changes sign exactly when the turn count is odd',
    Math.abs(w1 - 1) < 1e-6 && Math.abs(w2 - 2) < 1e-6 && Math.abs(w3 - 3) < 1e-6,
    `winding of arg(p^2 - 4q) over 1, 2 and 3 turns: ${w1.toFixed(9)}, ${w2.toFixed(9)}, ${w3.toFixed(9)} · ` +
    `the two roots differ by sqrt(p^2 - 4q), so an odd winding is an exchange and this is the whole of it`);

  /* and the collision locus really is where the collision is */
  let onLocus = 0;
  for (let k = 0; k < 24; k++) {
    const pp = C(Math.cos(k), Math.sin(2 * k) * 0.7);
    const v = X.embCollisionPoint(pp);
    const q = C(v[2], v[3]);
    const roots = X.embRootsOfMonic([C(1, 0), pp, q], 400);
    if (abs(sub(roots[0], roots[1])) < 1e-7) onLocus++;
  }
  ok('every point of the surface the laboratory draws in R^4 is a genuine collision: at twenty-four points of q = p^2/4 the two roots are the same root',
    onLocus === 24, `${onLocus}/24 · the surface is the image of p -> (p, p^2/4), a real 2-surface of codimension two in the R^4 of (p, q)`);
}

console.log('\n5 · SO(4), and why the isoclinic case is the Hopf fibration\n');
{
  let normRes = 0, isoRes = 0, worstNon = 0, compRes = 0;
  for (let k = 0; k < 200; k++) {
    const v = [Math.sin(k * 1.3), Math.cos(2.1 * k), Math.sin(3.7 * k + 1), Math.cos(5.3 * k)];
    const n0 = Math.hypot(v[0], v[1], v[2], v[3]);
    const r = X.embRot4(v, 0.7, 1.9);
    normRes = Math.max(normRes, Math.abs(Math.hypot(r[0], r[1], r[2], r[3]) - n0));
    isoRes = Math.max(isoRes, Math.abs(X.embIsoclinicAngle(v, 0.4) - 0.4));
    const w = X.embRot4(v, 0.4, 1.1), nn = n0 * n0;
    const ang = Math.acos(Math.min(1, Math.max(-1, (v[0] * w[0] + v[1] * w[1] + v[2] * w[2] + v[3] * w[3]) / nn)));
    worstNon = Math.max(worstNon, Math.abs(ang - 0.4));
    /* the one-parameter group law */
    const a = X.embRot4(X.embRot4(v, 0.31, 0.31), 0.47, 0.47), b = X.embRot4(v, 0.78, 0.78);
    compRes = Math.max(compRes, Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2], a[3] - b[3]));
  }
  ok('the four-dimensional viewfinder is a ROTATION: it preserves every length exactly, it composes as a one-parameter group when the two angles are equal, and in that isoclinic case every vector without exception turns through the same angle — while two unequal angles do not, by half a radian',
    normRes < 1e-14 && isoRes < 1e-14 && compRes < 1e-14 && worstNon > 0.4,
    `norm residual ${normRes.toExponential(2)} · isoclinic residual ${isoRes.toExponential(2)} over 200 directions · ` +
    `group law R(0.31)R(0.47) = R(0.78) to ${compRes.toExponential(2)} · with angles 0.4 and 1.1 the turning angle wanders by ${worstNon.toFixed(4)} rad`);

  /* THE POINT OF THAT PROPERTY. The orbits of an isoclinic rotation are the fibres of the
     Hopf map, so any two of them link exactly once — and the atlas's own Gauss linking
     integral, written for a different laboratory, is what says so. */
  const orbit = (v, M) => {
    const out = [];
    for (let s = 0; s < M; s++) {
      const w = X.embRot4(v, s / M * 2 * Math.PI, s / M * 2 * Math.PI);
      const d = 1 - w[3];
      out.push([w[0] / d, w[1] / d, w[2] / d]);
    }
    return out;
  };
  const unit = v => { const n = Math.hypot(v[0], v[1], v[2], v[3]); return v.map(x => x / n); };
  const A = orbit(unit([0.9, 0.2, 0.25, 0.1]), 400);
  const B = orbit(unit([0.15, 0.8, 0.3, -0.2]), 400);
  const A2 = orbit(unit([0.9, 0.2, 0.25, 0.1]), 1600);
  const B2 = orbit(unit([0.15, 0.8, 0.3, -0.2]), 1600);
  const lk1 = X.topoLinkPure(A, B), lk2 = X.topoLinkPure(A2, B2);
  ok('and THAT is why the isoclinic case matters: its orbits are the fibres of the Hopf map, so any two of them link exactly once — measured with the Gauss integral this atlas wrote for a different laboratory, and converging as the orbits are refined',
    Math.abs(Math.abs(lk1) - 1) < 5e-3 && Math.abs(Math.abs(lk2) - 1) < Math.abs(Math.abs(lk1) - 1) / 4,
    `linking ${lk1.toFixed(6)} at 400 points and ${lk2.toFixed(6)} at 1600 · defects ${Math.abs(Math.abs(lk1) - 1).toExponential(2)} and ${Math.abs(Math.abs(lk2) - 1).toExponential(2)} · ` +
    `the four-dimensional viewfinder of this laboratory and the fibration drawn in another are one motion`);
}

console.log('\n6 · the gate the molecular cut is missing, unchanged\n');
{
  const N = 12;
  const flat = X.embWeights(N, 0), spread = X.embWeights(N, 0.6);
  const c0 = X.civpCapacity(flat), c1 = X.civpCapacity(spread);
  ok('q_can = N_emb can hold while the pointwise gate C_U fails: raise the spread with the mean pinned at one and the capacity does not move, the certificate does, and the variance is the only other thing that changes',
    Math.abs(c0.q_can - N) < 1e-12 && Math.abs(c1.q_can - N) < 1e-12 &&
    c0.certificate_C_U === true && c1.certificate_C_U === false &&
    c0.weight_variance < 1e-24 && c1.weight_variance > 0.1 &&
    c1.capacity_equals_count === true,
    `flat: q_can = ${c0.q_can.toFixed(12)}, Var = ${c0.weight_variance.toExponential(1)}, C_U yes · ` +
    `spread: q_can = ${c1.q_can.toFixed(12)}, Var = ${c1.weight_variance.toExponential(3)}, C_U NO, and q_can = N_emb still says yes · ` +
    `a count becomes a capacity through a weight theorem or not at all`);

  /* gluing: exact at zero offset, and it fails the moment a mass moves past the tolerance */
  const roots = X.embPositions(N, 'spiral', 7).map(q => X.embZFromSphere(q));
  const A = roots.map((z, k) => ({ re: z.re, im: z.im, w: flat[k] }));
  const mk = off => A.slice().reverse().map((x, k) => ({ re: x.re, im: x.im, w: x.w + (k === 0 ? off : 0) }));
  const g0 = X.civpGluing(A, mk(0), 1e-12), g1 = X.civpGluing(A, mk(1e-9), 1e-12);
  ok('and the gluing of two atomic measures is exact when it should be and fails when it should: a mass perturbation three orders below anything visible breaks it, and the routine returns which atom and by how much',
    g0.compatible === true && g0.matched === N && g1.compatible === false &&
    Math.abs(g1.max_mass_defect - 1e-9) / 1e-9 < 1e-6,
    `offset 0: ${g0.matched}/${N} matched, defect ${g0.max_mass_defect.toExponential(1)}, compatible · ` +
    `offset 1e-9: defect ${g1.max_mass_defect.toExponential(6)} against a tolerance of 1e-12, NOT compatible · the recovered defect differs from the offset by ${(Math.abs(g1.max_mass_defect - 1e-9) / 1e-9).toExponential(1)} of itself, which is the rounding of adding 1e-9 to a weight of one and not a failure to measure it`);
}

console.log(`\n${fail === 0 ? '✔' : '✗'} ${pass} passed, ${fail} failed\n`);
process.exit(fail === 0 ? 0 : 1);
})().catch(e => { console.error(e); process.exit(1); });
